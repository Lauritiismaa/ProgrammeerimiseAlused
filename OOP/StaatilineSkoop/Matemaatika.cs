// Harjutus 2: staatilise klassi meetodeid kutsutakse ilma objekti loomata.
public static class Matemaatika
{
    public static int Ruut(int arv)
    {
        return arv * arv;
    }

    public static int Kuup(int arv)
    {
        return arv * arv * arv;
    }
}
